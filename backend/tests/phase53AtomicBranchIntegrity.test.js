import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import mongoose from 'mongoose';
import { Batch, BATCH_STATUS } from '../src/models/batch.model.js';
import { Branch } from '../src/models/branch.model.js';
import { Order, ORDER_STATUS } from '../src/models/order.model.js';
import { InventoryAudit, INVENTORY_ACTION_TYPES } from '../src/models/inventory.model.js';
import { ApiError } from '../src/utils/ApiError.js';

describe('Phase 5.3: Minimal Atomic Branch Integrity Fix Test Suite', () => {
  const storeAId = new mongoose.Types.ObjectId();
  const storeBId = new mongoose.Types.ObjectId();
  const sellerAId = new mongoose.Types.ObjectId();
  const customerId = new mongoose.Types.ObjectId();

  const primaryBranchA = new Branch({
    storeId: storeAId,
    sellerId: sellerAId,
    name: 'Primary Hub Indiranagar',
    address: { street: '100ft Rd', city: 'Bangalore', state: 'Karnataka', pincode: '560038' },
    contactPhone: '9876543210',
    isPrimary: true,
    isActive: true,
  });

  const secondaryBranchA = new Branch({
    storeId: storeAId,
    sellerId: sellerAId,
    name: 'Secondary Hub Koramangala',
    address: { street: '80ft Rd', city: 'Bangalore', state: 'Karnataka', pincode: '560095' },
    contactPhone: '9876543211',
    isPrimary: false,
    isActive: true,
  });

  const foreignBranchB = new Branch({
    storeId: storeBId,
    sellerId: new mongoose.Types.ObjectId(),
    name: 'Foreign Store Branch',
    address: { street: 'MG Rd', city: 'Bangalore', state: 'Karnataka', pincode: '560001' },
    contactPhone: '9876543212',
    isPrimary: true,
    isActive: true,
  });

  // =========================================================================
  // 1. Checkout Wins the Race: Stock Deduction Prevents Stale Reassignment
  // =========================================================================
  describe('1. Checkout Wins the Race', () => {
    it('rejects reassignment with 409 conflict when concurrent checkout deducts stock first', () => {
      // In-memory document state at start of updateBatchService
      const initialBatch = {
        _id: new mongoose.Types.ObjectId(),
        branchId: primaryBranchA._id,
        quantity: 10,
        reservedQuantity: 0,
      };

      // Checkout executes first and decrements quantity from 10 to 7
      const databaseBatch = {
        _id: initialBatch._id,
        branchId: primaryBranchA._id,
        quantity: 7, // modified by concurrent checkout
        reservedQuantity: 0,
      };

      // Atomic Compare-And-Set filter used by updateBatchService
      const atomicCondition = {
        _id: initialBatch._id,
        branchId: initialBatch.branchId || null,
        quantity: initialBatch.quantity, // expects 10
        reservedQuantity: 0,
      };

      // Simulation of Batch.findOneAndUpdate(atomicCondition, atomicUpdate)
      const matchesCondition =
        databaseBatch._id.toString() === atomicCondition._id.toString() &&
        databaseBatch.branchId.toString() === atomicCondition.branchId.toString() &&
        databaseBatch.quantity === atomicCondition.quantity &&
        databaseBatch.reservedQuantity === atomicCondition.reservedQuantity;

      assert.equal(matchesCondition, false, 'Condition must not match because stock quantity changed');

      let error = null;
      if (!matchesCondition) {
        error = new ApiError(
          409,
          'Concurrent modification conflict: Batch stock, reservation, or branch was modified by another operation during reassignment. Please refresh and try again.',
          'CONCURRENT_REASSIGNMENT_CONFLICT'
        );
      }

      assert.ok(error);
      assert.equal(error.statusCode, 409);
      assert.equal(error.errorCode, 'CONCURRENT_REASSIGNMENT_CONFLICT');
      // Verify database batch was NOT overwritten
      assert.equal(databaseBatch.quantity, 7);
      assert.equal(databaseBatch.branchId.toString(), primaryBranchA._id.toString());
    });
  });

  // =========================================================================
  // 2. Reassignment Wins the Race: Checkout Cannot Deduct From Reassigned Batch
  // =========================================================================
  describe('2. Reassignment Wins the Race', () => {
    it('rejects checkout deduction when batch was reassigned away from selected branch', () => {
      const batchId = new mongoose.Types.ObjectId();

      // Batch was reassigned to secondaryBranchA before checkout atomic update runs
      const databaseBatch = {
        _id: batchId,
        branchId: secondaryBranchA._id,
        quantity: 10,
      };

      // Checkout is attempting to deduct for primaryBranchA
      const checkoutBranch = primaryBranchA;
      const requestedQty = 3;

      // Query generated by createOrderService
      const query = {
        _id: batchId,
        quantity: { $gte: requestedQty },
      };
      if (checkoutBranch) {
        if (checkoutBranch.isPrimary) {
          query.$or = [{ branchId: checkoutBranch._id }, { branchId: null }];
        } else {
          query.branchId = checkoutBranch._id;
        }
      }

      // Evaluate match against databaseBatch
      const isMatch =
        databaseBatch.quantity >= requestedQty &&
        (query.$or
          ? query.$or.some(
              (cond) =>
                (cond.branchId === null && databaseBatch.branchId === null) ||
                (cond.branchId && cond.branchId.toString() === databaseBatch.branchId?.toString())
            )
          : query.branchId?.toString() === databaseBatch.branchId?.toString());

      assert.equal(isMatch, false, 'Deduction query must fail because batch belongs to another branch');
    });
  });

  // =========================================================================
  // 3. Primary Branch Accepts Legacy Lots (branchId: null)
  // =========================================================================
  describe('3. Primary Branch Legacy Lot Policy', () => {
    it('accepts legacy batch with branchId: null during primary-branch checkout', () => {
      const legacyBatch = {
        _id: new mongoose.Types.ObjectId(),
        branchId: null,
        quantity: 8,
      };

      const checkoutBranch = primaryBranchA;
      const requestedQty = 2;

      const query = {
        _id: legacyBatch._id,
        quantity: { $gte: requestedQty },
      };
      if (checkoutBranch.isPrimary) {
        query.$or = [{ branchId: checkoutBranch._id }, { branchId: null }];
      } else {
        query.branchId = checkoutBranch._id;
      }

      const isMatch =
        legacyBatch.quantity >= requestedQty &&
        query.$or.some(
          (cond) =>
            (cond.branchId === null && legacyBatch.branchId === null) ||
            (cond.branchId && cond.branchId.toString() === legacyBatch.branchId?.toString())
        );

      assert.equal(isMatch, true, 'Primary branch checkout must accept legacy unassigned lots');
    });
  });

  // =========================================================================
  // 4. Secondary Branch Strictly Rejects Legacy and Foreign Lots
  // =========================================================================
  describe('4. Secondary Branch Strict Isolation', () => {
    it('rejects legacy batch (branchId: null) during secondary-branch checkout', () => {
      const legacyBatch = {
        _id: new mongoose.Types.ObjectId(),
        branchId: null,
        quantity: 5,
      };

      const checkoutBranch = secondaryBranchA; // Non-primary
      const requestedQty = 1;

      const query = {
        _id: legacyBatch._id,
        quantity: { $gte: requestedQty },
      };
      if (checkoutBranch.isPrimary) {
        query.$or = [{ branchId: checkoutBranch._id }, { branchId: null }];
      } else {
        query.branchId = checkoutBranch._id;
      }

      const isMatch =
        legacyBatch.quantity >= requestedQty &&
        query.branchId?.toString() === legacyBatch.branchId?.toString();

      assert.equal(isMatch, false, 'Secondary branch must never fulfill legacy lots');
    });

    it('rejects foreign store branch batch during checkout', () => {
      const foreignBatch = {
        _id: new mongoose.Types.ObjectId(),
        branchId: foreignBranchB._id,
        quantity: 10,
      };

      const checkoutBranch = secondaryBranchA;
      const requestedQty = 2;

      const query = {
        _id: foreignBatch._id,
        quantity: { $gte: requestedQty },
        branchId: checkoutBranch._id,
      };

      const isMatch =
        foreignBatch.quantity >= requestedQty &&
        query.branchId.toString() === foreignBatch.branchId.toString();

      assert.equal(isMatch, false, 'Checkout must strictly reject foreign store batches');
    });
  });

  // =========================================================================
  // 5. Compensation Rollback across Multi-Batch Checkout
  // =========================================================================
  describe('5. Compensation Rollback on Multi-Batch Failure', () => {
    it('restores earlier batch deductions when a later batch fails due to concurrency conflict', async () => {
      const batchA = { _id: new mongoose.Types.ObjectId(), quantity: 10, soldQuantity: 0 };
      const batchB = { _id: new mongoose.Types.ObjectId(), quantity: 2, soldQuantity: 0 };

      const deductionsMade = [];

      // Deduction 1 on Batch A succeeds
      batchA.quantity -= 4;
      batchA.soldQuantity += 4;
      deductionsMade.push({ batchId: batchA._id, quantity: 4, ref: batchA });

      // Deduction 2 on Batch B fails due to concurrent conflict (requested 5, available 2)
      let checkoutError = null;
      try {
        if (batchB.quantity < 5) {
          throw new ApiError(409, 'Conflict on batch B', 'CONCURRENT_CHECKOUT_CONFLICT');
        }
      } catch (err) {
        checkoutError = err;
        // Rollback earlier deductions
        for (const ded of deductionsMade) {
          ded.ref.quantity += ded.quantity;
          ded.ref.soldQuantity -= ded.quantity;
        }
      }

      assert.ok(checkoutError);
      assert.equal(batchA.quantity, 10, 'Batch A stock must be completely restored by compensation');
      assert.equal(batchA.soldQuantity, 0);
      assert.equal(batchB.quantity, 2);
    });
  });

  // =========================================================================
  // 6. Active Orders Block Reassignment
  // =========================================================================
  describe('6. Active Order Guard Preservation', () => {
    it('blocks branch reassignment when an active unfulfilled order references the batch', () => {
      const batch = {
        _id: new mongoose.Types.ObjectId(),
        batchNumber: 'LOT-ACTIVE-ORDER-CHECK',
        reservedQuantity: 0,
      };

      const activeOrder = {
        orderNumber: 'ORD-BLOCK-001',
        status: ORDER_STATUS.READY_FOR_PICKUP,
      };

      assert.throws(
        () => {
          if (activeOrder) {
            throw new ApiError(
              400,
              `Cannot reassign branch: Batch [${batch.batchNumber}] is allocated to active order [${activeOrder.orderNumber}] in status [${activeOrder.status}]. Fulfill or cancel the order first.`,
              'BATCH_REASSIGNMENT_UNSAFE'
            );
          }
        },
        (err) => {
          assert.equal(err.statusCode, 400);
          assert.equal(err.errorCode, 'BATCH_REASSIGNMENT_UNSAFE');
          assert.match(err.message, /READY_FOR_PICKUP/);
          return true;
        }
      );
    });
  });

  // =========================================================================
  // 7. Audit Integrity: Failed Reassignment Does Not Create False Audit
  // =========================================================================
  describe('7. Audit Integrity on Failed Reassignment', () => {
    it('ensures no audit record is created when atomic conditional update fails', async () => {
      const audits = [];

      const executeAtomicReassignment = async (shouldFail) => {
        if (shouldFail) {
          throw new ApiError(409, 'Conflict', 'CONCURRENT_REASSIGNMENT_CONFLICT');
        }
        audits.push({ actionType: INVENTORY_ACTION_TYPES.STOCK_ADJUSTMENT });
      };

      await assert.rejects(
        async () => {
          await executeAtomicReassignment(true);
        },
        (err) => {
          assert.equal(err.errorCode, 'CONCURRENT_REASSIGNMENT_CONFLICT');
          return true;
        }
      );

      assert.equal(audits.length, 0, 'No audit record may be written when reassignment fails');
    });
  });

  // =========================================================================
  // 8. Order Cancellation & Stock Invariant Preservation
  // =========================================================================
  describe('8. Order Cancellation Invariant Preservation', () => {
    it('restores stock strictly to original order branch upon cancellation', () => {
      const originalBranch = primaryBranchA;
      const batch = {
        _id: new mongoose.Types.ObjectId(),
        branchId: originalBranch._id,
        quantity: 6,
        soldQuantity: 4,
      };

      const order = {
        _id: new mongoose.Types.ObjectId(),
        orderNumber: 'ORD-CANCEL-VERIFY-001',
        status: ORDER_STATUS.PLACED,
        branchId: originalBranch._id,
        allocatedQuantity: 4,
      };

      // Order cancelled -> stock returned to batch
      batch.quantity += order.allocatedQuantity;
      batch.soldQuantity -= order.allocatedQuantity;

      assert.equal(batch.quantity, 10);
      assert.equal(batch.soldQuantity, 0);
      assert.equal(batch.branchId.toString(), order.branchId.toString());
    });
  });
});

